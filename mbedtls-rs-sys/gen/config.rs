use std::collections::BTreeMap;
use std::convert::Infallible;
use std::path::Path;
use std::str::FromStr;
use std::sync::LazyLock;
use std::{fmt, fs, io};

use regex::Regex;

static CONFIG_RE: LazyLock<Regex> = LazyLock::new(|| {
    // This little beast of a regex is used to parse the mbedtls_config.h
    // header to extract the various configuration options.
    //
    // The regex extracts the following named capture groups:
    //
    // - `disabled`: If this group is present, the config option is
    //               disabled (i.e. it's commented out).
    // - `ident`: The identifier of the config option without the `MBEDTLS_`
    //            prefix.
    // - `value`: The value of the config option, if it has one.
    //
    // See: <https://regex101.com/r/u5XNfA/1>
    Regex::new(
        r#"(?mux)
        # Define might be commented out
        (?<disabled> // )? \ *
        # Start of the define
        \#define\ +
        # Identifier
        MBEDTLS_(?<ident> [^\ \n]+ )
        # Optional value
        (?:
        \ + (?<value> .*? )
        )?
        # Some definitions end with a comment
        (?: /\* .+ )?
        \n
    "#,
    )
    .unwrap()
});

/// Compile-time configuration for MbedTLS.
///
/// This encapsulates the various configuration options present in the
/// `mbedtls_config.h` header file.
/// This type implements `FromStr` to parse the config from the header file,
/// and `Display` to generate the header file from the config.
/// This process is extremely lossy. We don't bother preserving any comments
/// or even the original order of the options.
///
/// We're deliberately very strict when it comes to modifying the config.
/// The [`add`][Self::add] method refuses to modify existing options, and the
/// [`set`][Self::set] method refuses to define unknown options or change the
/// type of existing options.
/// This helps us ensure that the config we generate matches up with what
/// MbedTLS expects.
#[derive(Debug)]
pub struct MbedtlsConfig {
    options: BTreeMap<Box<str>, Value>,
}

impl MbedtlsConfig {
    /// Loads the MbedTLS config from a header file.
    ///
    /// The header file is expected to contain `#define` directives for the
    /// various config options, optionally commented out if they are disabled.
    pub fn load_from_header(path: &Path) -> io::Result<Self> {
        let content = fs::read_to_string(path)?;
        match content.parse() {
            Ok(config) => Ok(config),
            // Prove to the compiler that errors are impossible.
            Err(infallible) => match infallible {},
        }
    }

    /// Writes the MbedTLS config to a header file.
    pub fn write_to_path(&self, path: &Path) -> io::Result<()> {
        let contents = self.to_string();
        fs::write(path, contents)
    }

    /// Explicitly adds a config option.
    ///
    /// This function can be used to define our own config options for our
    /// alternative definitions.
    /// It must not be used for MbedTLS config options.
    ///
    /// # Panics
    ///
    /// Panics if the config option already exists.
    pub fn add(&mut self, ident: &str, value: impl Into<Value>) -> &mut Self {
        let value = value.into();
        let old = self.options.insert(ident.into(), value);
        if let Some(old) = old {
            panic!("config option '{ident}' already exists with a value of '{old:?}'");
        }
        self
    }

    /// Sets the value of a literal config option.
    ///
    /// # Panics
    ///
    /// Panics if the config option does not exist or if the value is of the
    /// wrong type.
    pub fn set(&mut self, ident: &str, value: impl Into<Value>) -> &mut Self {
        let Some(entry) = self.options.get_mut(ident) else {
            panic!("config option '{ident}' does not exist");
        };
        let value = value.into();
        if !entry.matches_type(&value) {
            panic!("config option '{ident}' is of the wrong type for the provided value (existing value: {entry:?})");
        }
        *entry = value;
        self
    }
}

impl fmt::Display for MbedtlsConfig {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("// This file is generated by mbedtls-rs-sys. Do not edit manually.\n")?;
        for (ident, value) in &self.options {
            if value.disabled() {
                f.write_str("// ")?;
            }
            write!(f, "#define MBEDTLS_{ident}")?;
            if let ValueInner::Literal { value, .. } = &value.0 {
                write!(f, " {value}")?;
            }
            f.write_str("\n")?;
        }
        Ok(())
    }
}

impl FromStr for MbedtlsConfig {
    type Err = Infallible;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let options = CONFIG_RE
            .captures_iter(s)
            .map(|captures| config_entry_from_captures(&captures))
            .collect();
        Ok(Self { options })
    }
}

/// A MbedTLS config value.
///
/// Used by [`MbedtlsConfig`].
#[derive(Debug)]
pub struct Value(ValueInner);

#[derive(Debug)]
enum ValueInner {
    /// A define with a literal value.
    Literal { value: Box<str>, disabled: bool },
    /// A define whose presence in the config controls a feature.
    Presence(bool),
}

impl Value {
    /// Returns true if the config option is disabled.
    ///
    /// For a presence-based option, this means that the option is not present
    /// in the config. This results in the feature controlled by the option
    /// being turned off.
    /// Literal options are also missing from the config when they are
    /// disabled, but the consequence is typically that MbedTLS will fall back
    /// to a default value.
    const fn disabled(&self) -> bool {
        match &self.0 {
            ValueInner::Literal { disabled, .. } => *disabled,
            ValueInner::Presence(present) => !*present,
        }
    }

    /// Returns true if the config option has the same type as another value.
    ///
    /// The "type" of an option is either "literal" or "presence".
    const fn matches_type(&self, other: &Self) -> bool {
        matches!(
            (&self.0, &other.0),
            (ValueInner::Literal { .. }, ValueInner::Literal { .. })
                | (ValueInner::Presence(_), ValueInner::Presence(_))
        )
    }
}

impl From<bool> for Value {
    fn from(value: bool) -> Self {
        Self(ValueInner::Presence(value))
    }
}

impl From<&str> for Value {
    fn from(value: &str) -> Self {
        Self(ValueInner::Literal {
            value: value.into(),
            disabled: false,
        })
    }
}

impl From<String> for Value {
    fn from(value: String) -> Self {
        Self(ValueInner::Literal {
            value: value.into(),
            disabled: false,
        })
    }
}

/// Parses a single config entry from the regex captures.
///
/// See the documentation of [`CONFIG_RE`] for details on the capture groups.
fn config_entry_from_captures(captures: &regex::Captures) -> (Box<str>, Value) {
    let ident = captures
        .name("ident")
        .expect("'ident' should always be present")
        .as_str()
        .into();
    let disabled = captures.name("disabled").is_some();
    let value = if let Some(value) = captures.name("value") {
        Value(ValueInner::Literal {
            value: value.as_str().into(),
            disabled,
        })
    } else {
        Value(ValueInner::Presence(!disabled))
    };
    (ident, value)
}
